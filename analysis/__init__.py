# 논문용 분석 (LLM 호출 없음)
#
# 이미 돌린 실행 기록(trace.jsonl)만으로 논문에 들어갈 표와 그림을 만든다.
#
#   dialogues   → 기록에서 대상별 대화(질문·원래 답변에서 뽑은 관찰)를 읽는다
#   populations → 기준 집단 변형 (크기·구성)과 공통 온톨로지
#   simulate    → 같은 관찰을 조건(방어 방식, k_req, 기준 집단, 일반화 한도, 추출 누락)만 바꿔 다시 판정한다
#   stats       → 부트스트랩 신뢰구간, 짝 검정, 생존 곡선, 무릎점
#   figures     → 그림 3개 (위험 궤적 / 보호–유용성 / 민감도)
#   paper       → 표와 설명을 paper_report.md로, 재현 정보를 manifest.json으로
#
# 왜 다시 돌리지 않고 다시 계산하는가
#   --paired 실행에서는 모든 조건이 같은 질문과 같은 원래 답변(raw)을 쓴다. 대상 AI의 답변은 방어 조건에
#   따라 달라지지 않으므로, 원래 답변에서 뽑은 관찰만 있으면 방어 판단과 그 결과는 기록만으로 다시 계산된다.
#   다른 점은 고친 답변의 문장이다. 여기서는 "Defender가 허용한 값만 공개된다"고 가정한다 (이상적 재작성).
#   이 가정이 실제 실행과 얼마나 맞는지는 consistency 표로 따로 확인한다.
#
# 이 패키지는 실행 코드(orchestrator, adapters 등)를 읽기만 한다. 실행 코드는 이 패키지를 import하지 않는다.
